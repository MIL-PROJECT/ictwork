const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');

// Owned synthetic profile only; no fixtures are copied to the actual user's DB.
module.exports=async function verifyOperations(page,origin,evidence) {
  const get=async suffix=>{const r=await page.request.get(origin+'/api/operations'+suffix);assert.equal(r.status(),200,await r.text());return r.json();};
  const headers=()=>page.context().cookies(origin).then(cookies=>({'X-XSRF-TOKEN':decodeURIComponent(cookies.find(c=>c.name==='XSRF-TOKEN').value)}));
  const put=async(id,data)=>page.request.put(origin+'/api/operations/'+id+'/status',{headers:await headers(),data});
  assert.deepEqual((await get('')).items,[],'New database must not contain fabricated legacy systems');
  const me=await (await page.request.get(origin+'/api/me')).json();
  await page.goto(origin+'/operations');
  await page.getByRole('button',{name:'체계 등록',exact:true}).click();
  const form=page.getByRole('dialog');
  await form.getByLabel('관리 부서',{exact:true}).selectOption(String(me.departmentId));
  await form.getByLabel('코드',{exact:true}).fill('QA-OPS-001');
  await form.getByLabel('체계명',{exact:true}).fill('시연 기반통신');
  await form.getByLabel('분류',{exact:true}).fill('기반통신');
  await form.getByLabel('운용률 (%)',{exact:true}).fill('99.75');
  await form.getByLabel('비고',{exact:true}).fill('격리 프로필의 시험 자료');
  await form.getByRole('button',{name:'저장',exact:true}).click();
  await page.getByRole('heading',{name:'시연 기반통신',exact:true}).waitFor();
  const id=Number(new URL(page.url()).searchParams.get('system'));
  let detail=await get('/'+id);
  assert.equal(detail.item.uptimePct,99.75);assert.equal(detail.history.length,1);
  assert.equal(await page.getByRole('img',{name:'변경 순서에 따른 기록 운용률 (0~100%)',exact:true}).count(),1);
  assert.equal(await page.locator('.ops-chart polygon').count(),0,'One recorded point must not imply a trend');
  await page.getByRole('button',{name:'상태·운용률 변경',exact:true}).click();
  await page.getByRole('dialog').getByLabel('상태',{exact:true}).selectOption('WATCH');
  await page.getByRole('dialog').getByLabel('운용률 (%)',{exact:true}).fill('94.25');
  await page.getByRole('dialog').getByRole('button',{name:'저장',exact:true}).click();
  await page.getByRole('heading',{name:'시연 기반통신',exact:true}).waitFor();
  detail=await get('/'+id);assert.equal(detail.item.status,'WATCH');assert.equal(detail.history.length,2);
  await page.screenshot({path:path.join(evidence,'operations-history.png'),animations:'disabled'});
  await page.getByRole('dialog').locator('.ops-actions').getByRole('button',{name:'닫기',exact:true}).click();
  await page.locator('.ops-table tbody').getByRole('button',{name:'체계 수정',exact:true}).click();
  await page.getByRole('dialog').getByLabel('체계명',{exact:true}).fill('시연 기반통신 수정');
  await page.getByRole('dialog').getByRole('button',{name:'저장',exact:true}).click();
  await page.getByRole('heading',{name:'시연 기반통신 수정',exact:true}).waitFor();
  detail=await get('/'+id);assert.equal(detail.item.status,'WATCH');assert.equal(detail.history.length,3);
  const invalid=await put(id,{status:'NORMAL',uptimePct:101,version:detail.item.version});assert.equal(invalid.status(),400);
  const concurrent=await Promise.all([put(id,{status:'NORMAL',uptimePct:98,version:detail.item.version}),put(id,{status:'FAULT',uptimePct:75,version:detail.item.version})]);
  assert.deepEqual(concurrent.map(r=>r.status()).sort(),[200,409],'One simultaneous edit wins without lost updates');
  detail=await get('/'+id);assert.equal(detail.history.length,4);
  const records=[detail];
  for(const [index,status] of ['NORMAL','INSPECTION','FAULT'].entries()) {
    const response=await page.request.post(origin+'/api/operations',{headers:await headers(),data:{departmentId:me.departmentId,code:'QA-OPS-00'+(index+2),name:['시연 작전통신','시연 사이버보호','시연 전송장비'][index],category:'시험 체계',status,uptimePct:96+index,remarks:'합성 시험 자료'}});
    assert.equal(response.status(),201,await response.text());records.push(await response.json());
  }
  const duplicate=await page.request.post(origin+'/api/operations',{headers:await headers(),data:{...detail.item,code:detail.item.code}});assert.equal(duplicate.status(),409);
  await page.goto(origin+'/operations?status=FAULT');
  await page.locator('.ops-table tbody tr').first().waitFor();
  assert.ok((await page.locator('.ops-table tbody').innerText()).includes('장애'));
  await page.goto(origin+'/operations?q=작전통신');
  await page.locator('.ops-table tbody tr').first().waitFor();assert.equal(await page.locator('.ops-table tbody tr').count(),1);
  await page.screenshot({path:path.join(evidence,'operations-search.png'),animations:'disabled'});
  await page.goto(origin+'/board');
  await page.waitForFunction(()=>document.querySelector('.board-metric-value')?.textContent==='4개');
  const data=await get('');const normal=data.items.filter(item=>item.status==='NORMAL').length;
  assert.equal((await page.locator('.board-metric-value').allTextContents())[1],normal+'개');
  await page.locator('.board-operation-row').first().click();
  await page.getByRole('dialog').waitFor();
  assert.ok(new URL(page.url()).searchParams.get('system'));
  await page.keyboard.press('Escape');
  // Delete one synthetic record through the confirmation UI; no real data used.
  const remove=records.pop();await page.goto(origin+'/operations?system='+remove.item.id);
  await page.getByRole('button',{name:'삭제',exact:true}).click();
  await page.getByRole('button',{name:'삭제 확정',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal((await page.request.get(origin+'/api/operations/'+remove.item.id)).status(),404);
  await page.goto(origin+'/operations');await page.locator('.ops-table tbody tr').first().waitFor();
  await page.screenshot({path:path.join(evidence,'operations-list.png'),animations:'disabled'});
  fs.writeFileSync(path.join(evidence,'operations-result.json'),JSON.stringify({success:true,syntheticOnly:true,concurrentStatuses:[200,409],invalidRate:400,duplicate:409,deletedId:remove.item.id,persisted:records.map(record=>({id:record.item.id,status:record.item.status,history:record.history.length}))},null,2));
  console.log('PASS real operations UI registration/edit/status/history/search, dashboard counts/deep link, concurrent conflict and soft deletion');
};
